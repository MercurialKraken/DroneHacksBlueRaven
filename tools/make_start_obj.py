#!/usr/bin/env python3
"""OFFLINE: the start rebuilt on 2026-11-07, from the numbers in maps/course.yaml `rebuilt_start:`, so a tape
measurement becomes a map and routes in one command:

    python tools/make_start_obj.py          # maps/course/start-2026-11-07.obj + CP2's line/direction in course.yaml
    python tools/make_start_obj.py --all    # ...then the SDF (tools/build_course_sdf.py), its checks of the start,
                                            # route v6 (tools/make_route_v6.py) and its clearance (tools/check_route.py)

Points are course coordinates (frame: course) or [forward, left] metres from the launch mark's centre (frame: mark),
whichever is easier to tape. Wall ends are the faces AT the CP2 gap, so the gap's free width is the distance between
Wall A's east end and Wall B's north-east end; each wall's thickness lies on the side away from the gap. CP2's line
is those two ends; its direction is their normal, pointing away from the launch mark. Waypoints, sims and offline
checks only: nothing reads this in flight.
"""
from __future__ import annotations

import argparse
import math
import re
import subprocess
import sys
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
COURSE = ROOT / "maps" / "course.yaml"
START_OBJ = ROOT / "maps" / "course" / "start-2026-11-07.obj"


def to_course(pts, frame: str, launch: dict) -> np.ndarray:
    """N x 2 course coordinates of points given in `frame` ('course', or 'mark': [forward, left] from the mark)."""
    P = np.asarray(pts, dtype=float).reshape(-1, 2)
    if frame == "course":
        return P
    if frame != "mark":
        raise ValueError(f"rebuilt_start.frame must be 'course' or 'mark', not {frame!r}")
    a = math.radians(float(launch["yaw_deg"]))
    f, l = P[:, 0], P[:, 1]
    return np.c_[float(launch["x"]) + f * math.cos(a) - l * math.sin(a),
                 float(launch["y"]) + f * math.sin(a) + l * math.cos(a)]


def start_geometry(cfg: dict) -> dict:
    rs, L = cfg["rebuilt_start"], cfg["launch"]
    frame = rs.get("frame", "course")
    g = {"A": to_course(rs["wall_a"], frame, L), "B": to_course(rs["wall_b"], frame, L),
         "cone": to_course([rs["cone"]], frame, L)[0], "t": float(rs.get("wall_thickness", 0.1016)),
         "h": float(rs.get("wall_height", 1.727)), "cone_size": float(rs.get("cone_size", 0.23)),
         "cone_h": float(rs.get("cone_height", 0.30)), "source": str(rs.get("source", "")),
         "launch": np.array([float(L["x"]), float(L["y"])])}
    if g["A"].shape != (2, 2) or g["B"].shape != (2, 2):
        raise ValueError("wall_a and wall_b need exactly two points each: [far end, gap end]")
    a_end, b_end = g["A"][1], g["B"][1]
    g["gap_mid"] = 0.5 * (a_end + b_end)
    g["gap_width"] = float(np.linalg.norm(b_end - a_end))
    v = (b_end - a_end) / g["gap_width"]
    n = np.array([v[1], -v[0]])
    g["gap_normal"] = n if n @ (g["gap_mid"] - g["launch"]) > 0 else -n
    return g


def _box(name: str, xy: list, z0: float, z1: float, base: int) -> list[str]:
    out = [f"g {name}"] + [f"v {x:.4f} {y:.4f} {z:.4f}" for z in (z0, z1) for x, y in xy]
    out += ["f " + " ".join(str(base + 1 + i) for i in f) for f in
            [(0, 1, 2, 3), (7, 6, 5, 4), (0, 4, 5, 1), (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)]]
    return out


def wall_footprint(p0: np.ndarray, p1: np.ndarray, t: float, away: np.ndarray) -> list[np.ndarray]:
    """The wall's footprint: the face from p0 to p1, and its thickness t on the side away from `away`."""
    d = (p1 - p0) / np.linalg.norm(p1 - p0)
    n = np.array([-d[1], d[0]])
    if (away - 0.5 * (p0 + p1)) @ n > 0:
        n = -n
    return [p0, p1, p1 + t * n, p0 + t * n]


def obj_text(g: dict) -> str:
    lines = ["# Start of the course as rebuilt by the organizers on 2026-11-07 (they withheld exact dimensions).",
             f"# Generated by tools/make_start_obj.py from maps/course.yaml rebuilt_start ({g['source']}).",
             "# Wall ends are the faces at the CP2 gap; each wall's thickness lies on the side away from the gap.",
             "# Boxes in the published OBJ's frame (x east, y north, z up, metres). Used with dronehacks-course-v3.obj,",
             "# whose maze dividers M1, M2, M3 were removed (course.yaml excludes them). Not the organizers' CAD.", ""]
    lines += _box("Start wall A", wall_footprint(g["A"][0], g["A"][1], g["t"], g["gap_mid"]), 0.0, g["h"], 0)
    lines += _box("Start wall B diagonal", wall_footprint(g["B"][0], g["B"][1], g["t"], g["gap_mid"]), 0.0, g["h"], 8)
    c, h = g["cone"], g["cone_size"] / 2
    lines += _box("Boulder 6 CP2 cone", [c + [-h, -h], c + [h, -h], c + [h, h], c + [-h, h]], 0.0, g["cone_h"], 16)
    return "\n".join(lines) + "\n"


def sync_cp2(text: str, g: dict) -> str:
    """course.yaml text with CP2's line = [Wall A gap end, Wall B gap end] and direction = their normal."""
    i = text.index("- id: CP2")
    j = text.find("- id:", i + 5)
    j = len(text) if j < 0 else j
    a, b, n = g["A"][1], g["B"][1], g["gap_normal"]
    block = re.sub(r"(\n\s+line: )\[\[[^\]]*\], \[[^\]]*\]\]",
                   lambda m: f"{m.group(1)}[[{a[0]:.3f}, {a[1]:.3f}], [{b[0]:.3f}, {b[1]:.3f}]]", text[i:j], count=1)
    block = re.sub(r"(\n\s+direction: )\[[^\]]*\]", lambda m: f"{m.group(1)}[{n[0]:.3f}, {n[1]:.3f}]", block, count=1)
    return text[:i] + block + text[j:]


def check_sdf(g: dict) -> list[tuple[bool, str]]:
    """The rebuilt start, as the SDF sees it: inside both walls and the cone, and the gap's centre clearance."""
    sys.path.insert(0, str(ROOT))
    from nav.course_map import CourseMap
    cm = CourseMap.load(ROOT / "maps" / "course_sdf.npz")
    out = []
    for name, (p0, p1) in (("Wall A", g["A"]), ("Wall B", g["B"])):
        fp = wall_footprint(p0, p1, g["t"], g["gap_mid"])
        inside = 0.5 * (fp[0] + fp[2])                               # the footprint's centre
        d = float(cm.distance(np.array([[*inside, 1.0]]))[0])
        out.append((d <= 0.0, f"inside {name} at ({inside[0]:+.3f}, {inside[1]:+.3f}): {d:+.3f} m (want <= 0)"))
    d = float(cm.distance(np.array([[*g["cone"], 0.15]]))[0])
    out.append((d <= 0.0, f"inside the cone: {d:+.3f} m (want <= 0)"))
    d = float(cm.distance(np.array([[*g["gap_mid"], 0.77]]))[0])
    half = g["gap_width"] / 2
    out.append((half - 0.045 <= d <= half + 0.01,
                f"CP2 gap centre at 0.77 m: {d:.3f} m clear (free width {g['gap_width']:.3f} m; want about "
                f"{half:.3f}); per side for a 0.56 m drone {(g['gap_width'] - 0.56) / 2 * 100:+.1f} cm"))
    return out


def run(cmd: list[str]) -> str:
    r = subprocess.run([sys.executable, *cmd], cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout[-3000:], r.stderr[-3000:], sep="\n")
        raise SystemExit(f"{' '.join(cmd)} failed ({r.returncode})")
    return r.stdout


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--all", action="store_true", help="also rebuild the SDF, check it, regenerate and check route v6")
    a = ap.parse_args(argv)
    text = COURSE.read_text(encoding="utf-8")
    g = start_geometry(yaml.safe_load(text))
    START_OBJ.write_text(obj_text(g), encoding="utf-8")
    new = sync_cp2(text, g)
    if new != text:
        COURSE.write_bytes(new.encode("utf-8"))
    print(f"wrote {START_OBJ.relative_to(ROOT)}; CP2 line {g['A'][1].round(3).tolist()} -> {g['B'][1].round(3).tolist()}"
          f", free width {g['gap_width']:.3f} m, normal {g['gap_normal'].round(3).tolist()}"
          + ("" if new == text else "; course.yaml CP2 updated"))
    if not a.all:
        print("next: python tools/make_start_obj.py --all  (SDF, checks, route v6, clearance)")
        return 0
    print(run(["tools/build_course_sdf.py", str(COURSE)]).strip().splitlines()[-1])
    results = check_sdf(g)
    for ok, line in results:
        print(("ok   " if ok else "FAIL ") + line)
    if not all(ok for ok, _ in results):
        return 1
    print(run(["tools/make_route_v6.py"]).strip())
    for f, key in (("route_v6_start2.json", "launch"), ("route_v6_start2_stage1.json", "launch"),
                   ("route_v6_start2_sim.json", "launch_sim")):
        out = run(["tools/check_route.py", f"routes/{f}", key]).splitlines()
        print(f"{f}: " + next(l.strip() for l in out if "straight segments" in l))
    return 0


if __name__ == "__main__":
    sys.exit(main())
